def download_with_roboflow(vertical: str, api_key: str, output_dir: str):
    """Download dataset using Roboflow API"""
    try:
        from roboflow import Roboflow
    except ImportError:
        print("ERROR: roboflow package not installed. Run:")
        print("  pip install roboflow")
        sys.exit(1)

    if vertical not in DATASETS:
        print(f"ERROR: Unknown vertical '{vertical}'. Choose from: {list(DATASETS.keys())}")
        sys.exit(1)

    ds = DATASETS[vertical]
    print(f"\n{'='*60}")
    print(f"Downloading: {ds['description']}")
    print(f"Workspace: {ds['workspace']}")
    print(f"Project: {ds['project']} v{ds['version']}")
    print(f"{'='*60}\n")

    rf = Roboflow(api_key=api_key)
    project = rf.workspace(ds["workspace"]).project(ds["project"])
    version = project.version(ds["version"])
    
    dataset = version.download(
        model_format="yolov8",
        location=os.path.join(output_dir, vertical)
    )
    
    print(f"\n✅ Dataset downloaded to: {os.path.join(output_dir, vertical)}")
    print(f"   Classes: {ds['classes']}")
    return dataset


def download_open_images_subset(vertical: str, output_dir: str, max_images: int = 500):
    """
    Alternative: Download from Open Images using FiftyOne (no API key needed).
    Good for traffic vertical since COCO classes overlap.
    """
    try:
        import fiftyone as fo
        import fiftyone.zoo as foz
    except ImportError:
        print("INFO: fiftyone not installed. Install with: pip install fiftyone")
        print("      Using Roboflow method instead.")
        return None

    class_map = {
        "traffic": ["Car", "Truck", "Bus", "Motorcycle", "Bicycle"],
        "safety": ["Person", "Helmet"],
    }

    if vertical not in class_map:
        print(f"Open Images download not configured for '{vertical}'")
        return None

    classes = class_map[vertical]
    print(f"Downloading {max_images} images from Open Images for classes: {classes}")

    dataset = foz.load_zoo_dataset(
        "open-images-v7",
        split="train",
        label_types=["detections"],
        classes=classes,
        max_samples=max_images,
    )
    
    print(f"✅ Downloaded {len(dataset)} images")
    return dataset


def create_sample_yaml(vertical: str, dataset_dir: str):
    """Create data.yaml for training if not already present"""
    yaml_path = os.path.join(dataset_dir, "data.yaml")
    if os.path.exists(yaml_path):
        print(f"data.yaml already exists at {yaml_path}")
        return yaml_path

    ds = DATASETS[vertical]
    classes = ds["classes"]
    
    yaml_content = f"""# VisionSync - {vertical.title()} Dataset
# Auto-generated by download_dataset.py

train: {os.path.join(dataset_dir, 'train', 'images').replace(os.sep, '/')}
val: {os.path.join(dataset_dir, 'valid', 'images').replace(os.sep, '/')}
test: {os.path.join(dataset_dir, 'test', 'images').replace(os.sep, '/')}

nc: {len(classes)}
names: {classes}
"""
    with open(yaml_path, 'w') as f:
        f.write(yaml_content)
    
    print(f"Created data.yaml at {yaml_path}")
    return yaml_path


def check_dataset_structure(dataset_dir: str):
    """Verify dataset directory structure"""
    required = ["train/images", "valid/images"]
    optional = ["test/images", "train/labels", "valid/labels"]
    
    print(f"\nChecking dataset structure in: {dataset_dir}")
    all_ok = True
    
    for d in required:
        path = os.path.join(dataset_dir, d)
        exists = os.path.exists(path)
        count = len(os.listdir(path)) if exists else 0
        status = f"✅ {count} files" if exists else "❌ MISSING"
        print(f"  {d}: {status}")
        if not exists:
            all_ok = False
    
    for d in optional:
        path = os.path.join(dataset_dir, d)
        exists = os.path.exists(path)
        count = len(os.listdir(path)) if exists else 0
        status = f"✅ {count} files" if exists else "⚠️  not found"
        print(f"  {d}: {status}")
    
    return all_ok


